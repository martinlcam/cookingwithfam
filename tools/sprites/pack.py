"""Build public/assets/food.png + .json from the PixelFoodThemedAssets pack in tools/raw.

    python3 tools/sprites/pack.py

Takes the outlined ("B") variant of every dish and drink, skips branded groceries
and film/TV items, splits the burger-ingredient strip into its layers, and writes a
Phaser JSONHash atlas plus src/assets/food_frames.ts and docs/food-preview.png.
"""
from __future__ import annotations
import io, json, os, re, sys, zipfile
sys.path.insert(0, os.path.dirname(__file__))
from PIL import Image, ImageDraw
from gen import pack, atlas_json, OUT, ROOT

ZIP = os.path.join(ROOT, "tools", "raw", "PixelFoodThemedAssets.zip")
KEEP_DIRS = ("32.32", "Drinks", "Other")
RENAME = {
    "baggett": "baguette", "tumber": "tumbler", "blueberry_tare": "blueberry_tart",
    "strawberry_chesse_cake": "strawberry_cheesecake", "lemon_cheese_cake": "lemon_cheesecake",
    "red_velvet_cake2": "red_velvet_slice", "red_velvet_cake3": "red_velvet_slice_2", "red_velvet_cake": "red_velvet_cake",
    "pumpkin_pie2": "pumpkin_pie_whole", "strawberry_cake2": "strawberry_cake_whole",
    "british_christmas_pudding": "christmas_pudding", "chocolate_mousse_dome": "chocolate_mousse",
    "coffee": "latte", "coffee_cup": "coffee", "oreo": "sandwich_cookie",
}
BURGER_LAYERS = ["bun_top", "lettuce_leaf", "tomato_slice", "cheese_slice", "patty", "bun_bottom"]

def snake(name: str) -> str:
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).replace(" ", "_").replace("-", "_").lower()
    s = re.sub(r"_+", "_", s)
    return RENAME.get(s, s)

def load(z: zipfile.ZipFile, name: str):
    try:
        im = Image.open(io.BytesIO(z.read(name))).convert("RGBA")
        im.load()
        return im
    except Exception:
        return None

def split_strip(im: Image.Image):
    """Split a vertical strip on fully transparent rows."""
    px = im.load()
    empty = [all(px[x, y][3] == 0 for x in range(im.width)) for y in range(im.height)]
    parts, start = [], None
    for y, e in enumerate(empty + [True]):
        if not e and start is None: start = y
        if e and start is not None:
            parts.append(im.crop((0, start, im.width, y))); start = None
    return parts

def main():
    z = zipfile.ZipFile(ZIP)
    names = [n for n in z.namelist() if n.lower().endswith(".png")]
    by_dir: dict[str, dict[str, str]] = {}
    for n in names:
        parts = n.split("/")
        if len(parts) != 3 or parts[1] not in KEEP_DIRS: continue
        by_dir.setdefault(parts[1], {})[parts[2][:-4]] = n
    sprites, skipped = [], []
    for d, files in by_dir.items():
        bases = sorted({f[:-1] if f.endswith("B") else f for f in files})
        for base in bases:
            if base == "BurgerIngredients":
                for layer, im in zip(BURGER_LAYERS, split_strip(load(z, files[base]))):
                    sprites.append((layer, im))
                continue
            im = load(z, files[base + "B"]) if base + "B" in files else None
            if im is None: im = load(z, files[base]) if base in files else None
            if im is None: skipped.append(base); continue
            sprites.append((snake(base), im))
    seen = {}
    for n, _ in sprites: seen[n] = seen.get(n, 0) + 1
    dupes = [n for n, c in seen.items() if c > 1]
    assert not dupes, f"duplicate frame names: {dupes}"
    sheet, frames = pack(sprites, max_w=512)
    sheet.save(os.path.join(OUT, "food.png"))
    with open(os.path.join(OUT, "food.json"), "w") as f:
        json.dump(atlas_json(frames, "food.png", sheet.width, sheet.height), f, indent=1)
    with open(os.path.join(ROOT, "src", "assets", "food_frames.ts"), "w") as f:
        f.write("// Generated by tools/sprites/pack.py. Do not edit.\n")
        f.write("export const FOOD_FRAMES = " + json.dumps(sorted(frames), indent=0).replace("\n", " ") + " as const;\n")
        f.write("export type FoodFrame = (typeof FOOD_FRAMES)[number];\n")
    # preview
    cols, cw, ch = 10, 104, 124
    rows = (len(sprites) + cols - 1) // cols
    pv = Image.new("RGBA", (cols * cw, rows * ch), (255, 244, 220, 255)); d = ImageDraw.Draw(pv)
    for i, (name, im) in enumerate(sorted(sprites)):
        x, y = (i % cols) * cw, (i // cols) * ch
        s = min(3, 96 / max(im.width, im.height))
        big = im.resize((max(1, int(im.width * s)), max(1, int(im.height * s))), Image.NEAREST)
        pv.alpha_composite(big, (x + (cw - big.width) // 2, y + 4 + (96 - big.height) // 2))
        d.text((x + 2, y + 104), name[:17], fill=(58, 33, 24)); d.text((x + 2, y + 114), name[17:34], fill=(58, 33, 24))
    pv.save(os.path.join(ROOT, "docs", "food-preview.png"))
    print(f"food: {len(sprites)} frames, sheet {sheet.width}x{sheet.height}; skipped (unreadable): {skipped}")

if __name__ == "__main__":
    main()
