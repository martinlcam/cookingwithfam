"""Original glyph shapes for the game font, drawn pixel by pixel.

Grid: up to 6 columns. Rows 0-9 are the cap height, baseline sits under row 9,
rows 10-12 are descenders. Lowercase x-height runs rows 3-9. '#' is fill.
Style target: chunky, bold, slab-ish letters with a gold gradient and a dark
outline, like a cheerful cooking game. Shapes are our own.
"""

G: dict[str, list[str]] = {}

def g(ch, rows, top=0):
    """Register a glyph. `top` is the grid row of the first string."""
    G[ch] = [""] * top + rows

